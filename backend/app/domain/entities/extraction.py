@dataclass(frozen=True)
class ExtractedActivity:
    """One activity read from a document; every data field is None when absent or ungrounded."""

    taxonomy: TaxonomyCode
    page: int
    evidence_text: str
    confidence: Decimal
    title: str | None = None
    role: str | None = None
    start_date: date | None = None
    end_date: date | None = None
    event_date: date | None = None
    term: str | None = None  # the duration as written ("por 2 anos"), never a computed date
    hours: Decimal | None = None
    course_hours: Decimal | None = None
    level: Level | None = None
    academic_period: str | None = None
    identifier: str | None = None
