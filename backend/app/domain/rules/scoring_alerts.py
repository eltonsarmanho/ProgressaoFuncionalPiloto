    """Why an activity row is not scored. These are reasons, not alerts."""

    SEM_ENQUADRAMENTO = "SEM_ENQUADRAMENTO"
    FORA_DO_INTERSTICIO = "FORA_DO_INTERSTICIO"
    DUPLICIDADE = "DUPLICIDADE"
    REJEITADA = "REJEITADA"
    GRUPO_NAO_CONTA = "GRUPO_NAO_CONTA"
    SEM_TABELA = "SEM_TABELA"
