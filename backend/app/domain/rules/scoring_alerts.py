    TABELA_DE_OUTRA_UNIDADE = "TABELA_DE_OUTRA_UNIDADE"
    TABELA_PENDENTE_VALIDACAO = "TABELA_PENDENTE_VALIDACAO"
    TABELA_FORA_DE_VIGENCIA = "TABELA_FORA_DE_VIGENCIA"
    SEM_EXTENSAO_OU_PESQUISA = "SEM_EXTENSAO_OU_PESQUISA"
    MINIMO_NAO_DEFINIDO = "MINIMO_NAO_DEFINIDO"
    INTERSTICIO_PARCIAL = "INTERSTICIO_PARCIAL"
    DATA_AUSENTE = "DATA_AUSENTE"
    SEM_COMPROVANTE = "SEM_COMPROVANTE"
    PONTOS_AJUSTADOS_MANUALMENTE = "PONTOS_AJUSTADOS_MANUALMENTE"
    LIMITE_APLICADO = "LIMITE_APLICADO"


